// Build-time generator: reads the admin-facing markdown docs from /docs and
// emits src/lib/help/content.generated.ts as a bundled module. Runs via the
// `predev` / `prebuild` npm lifecycle hooks, so the app NEVER reads /docs from
// the filesystem at request time (which is unreliable on Vercel's traced
// serverless functions). The docs stay the single source of truth in /docs.
//
// Run directly: node scripts/generate-help-content.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// slug -> source file in /docs. The slug is the URL segment under /admin/help.
const DOCS = {
  "rachel-admin-guide": "rachel-admin-guide.md",
  "admin-email-reference": "admin-email-reference.md",
  "admin-faq": "admin-faq.md",
  "booking-invitation-flow": "booking-invitation-flow.md",
};

const content = {};
const missing = [];
for (const [slug, file] of Object.entries(DOCS)) {
  try {
    content[slug] = readFileSync(join(root, "docs", file), "utf8");
  } catch {
    missing.push(file);
  }
}

if (missing.length > 0) {
  console.error(`[generate-help-content] Missing docs: ${missing.join(", ")}`);
  process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/generate-help-content.mjs — DO NOT EDIT.
// Edit the source markdown in /docs and rebuild (predev/prebuild regenerate this).
export const HELP_CONTENT: Record<string, string> = ${JSON.stringify(content, null, 2)};
`;

const outPath = join(root, "src", "lib", "help", "content.generated.ts");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, "utf8");
console.log(`[generate-help-content] Wrote ${outPath} (${Object.keys(content).length} docs).`);
